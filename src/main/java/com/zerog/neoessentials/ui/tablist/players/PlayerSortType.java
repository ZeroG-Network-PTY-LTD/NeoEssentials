package com.zerog.neoessentials.ui.tablist.players;

/**
 * Enum defining different ways to sort players in the tablist
 */
public enum PlayerSortType {
    /**
     * Sort players alphabetically by name
     */
    NAME,
    
    /**
     * Sort players by their rank/permission group
     */
    RANK,
    
    /**
     * Sort players by total playtime
     */
    PLAYTIME
}
