package com.zerog.neoessentials.config;

/**
 * Enum representing different storage types for NeoEssentials data
 */
public enum StorageType {
    /**
     * JSON file storage (default)
     */
    JSON,
    
    /**
     * SQLite database storage
     */
    SQLITE,
    
    /**
     * MySQL database storage
     */
    MYSQL
}
